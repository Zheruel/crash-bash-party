// Regenerates client/disc/levels.ts from ../assets/arenas.json (index metadata only; no disc data).
//   node scripts/gen-levels.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const a = JSON.parse(fs.readFileSync(path.resolve(here, '../../assets/arenas.json'), 'utf8'));
const idx = (f) => (f ? f.index : null);
const levels = a.levels.map((l) => ({
  id: l.level_id,
  name: l.name,
  familyCode: parseInt(l.family_code, 16),
  family: l.family,
  arenaVariant: l.arena_variant,
  altVariant: l.alt_variant,
  textFile: idx(l.files.text),
  musicFile: idx(l.files.music_t10),
  sfxFiles: (l.files.sfx_bank_t0c ?? []).map((f) => f.index),
  animTableFile: idx(l.files.character_anim_table),
  modelTextureGroups: l.files.model_texture_groups ?? [],
  modelTextureConfidence: l.files.model_texture_confidence,
}));
const groups = a.groups.map((g) => ({ group: g.group, firstFile: g.first_file, count: g.count, types: g.types }));
const out = `// GENERATED by scripts/gen-levels.mjs from assets/arenas.json - do not edit.
// File indices into CRASHBSH.DAT only; contains no game data.
import type { FileGroup, LevelInfo } from './types';

export const LEVELS: readonly LevelInfo[] = ${JSON.stringify(levels)};

export const FILE_GROUPS: readonly FileGroup[] = ${JSON.stringify(groups)};
`;
fs.writeFileSync(path.resolve(here, '../client/disc/levels.ts'), out);
console.log(`levels=${levels.length} groups=${groups.length}`);
