"""Extract Crash Dash's collision meshes and course edges from the USA disc models."""
import json
import math
import struct
from pathlib import Path

from t29 import parse_mesh, u32

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'web/shared/games/dashCollisionData.ts'
prefix = '// Generated by tools/dash_collision.py from disc models 0637, 0639, 0641 and 0643.\n'
wall_groups, hub, falls = {}, {}, {}
for name, model, level in [('dante', 637, 26), ('toxic', 639, 24), ('splash', 641, 25), ('dot', 643, 23)]:
    data = (ROOT / f'disc/dat/{model:04}.t29.bin').read_bytes()
    placements = json.loads((ROOT / f'assets/stages/placements/L{level}.json').read_text())
    surfaces = []
    for obj in placements['objects']:
        entry = int(obj['part'].split('_')[1], 16)
        normals = u32(data, entry + 32)
        if not normals or int(obj['flags'], 16) & 0x8000:
            continue
        mesh = parse_mesh(data, entry, None, None, 0)
        faces = []
        for tri in mesh.tris:
            a, b, c = tri['v']
            # Collision uses strip order regardless of the GPU winding flag.
            normal = struct.unpack_from('<3h', data, entry + 32 + normals + 8 * c)
            faces.append([*mesh.pos[min(a,b)], *mesh.pos[max(a,b)], *mesh.pos[c], normal[0], normal[2]])
        surfaces.append(faces)
    wall_groups[name] = surfaces
    header = data.index(struct.pack('<3I', 8192, 8192, 8192))
    table = header + 20 + u32(data, header + 20)
    def edges(index):
        ptr = table + 4 + 4 * index
        base = ptr + u32(data, ptr)
        return [struct.unpack_from('<8i', data, base + 72 + 56 * i) for i in range(u32(data, base + 56))]
    # FUN_8008c4c8 uses the signed projections onto each authored edge normal.
    def planes(index):
        result = []
        for x, _, z, _, _, _, _, yaw in edges(index):
            angle = -yaw * math.tau / 4096
            result.append([x, z, round(4096 * math.cos(angle)), round(4096 * math.sin(angle))])
        return result
    hub[name] = planes(0)
    if name == 'dot':
        outer = planes(3)
    if name in ('splash', 'dot'):
        falls[name] = [[r[0], r[2], r[3], r[5], r[6], r[7]] for r in edges(1)]
    if name == 'splash':
        group = 0x44 + u32(data, 0x44)
        frames = u32(data, group)
        tips = []
        for i in range(u32(data, group + 8)):
            ptr = frames + (1 + i) * 16
            box = ptr + u32(data, ptr)
            count, xmin, _, zmin, xmax, top, zmax, flags = struct.unpack_from('<H6hI', data, box + 2)
            assert (count, xmin, xmax, top, zmax, flags) == (1, -176, 176, -357, -778, 0)
            tips.append(-zmin)
def export(name, typ, value):
    return f'export const {name}: {typ} = ' + json.dumps(value, separators=(',', ':')) + ';\n'
OUT.write_text(prefix + export('TRACK_WALLS', 'Record<string, number[][][]>', wall_groups)
               + export('AI_HUB', 'Record<string, number[][]>', hub)
               + export('DOT_OUTER', 'number[][]', outer)
               + export('FALL_EDGE', 'Record<string, number[][]>', falls)
               + export('SPOKE_REACH', 'number[]', tips))
