#!/usr/bin/env python3
"""Decode the effect scripts of Crash Bash object packs (type-0x29 files) to a TS data module.

usage: python3 -I tools/fxscripts.py DISC_DAT_DIR OUT.ts MODEL[:SCRIPT,SCRIPT...] ...
  e.g. python3 -I tools/fxscripts.py disc/dat web/client/games/fxScripts.ts 738 343:0,1,2 736:
  (MODEL = every script, MODEL: = only the sprite flags of its parts)

The game plays these through effect object 0x1605 (init FUN_8008b510, update FUN_8008bb48): a pack carries
`u32 +0x48` scripts, offset table at `+0x4c` (self-relative, entries self-relative). Script: {tracks, nodes,
duration, ...} then self-relative track pointers at +0x1c. Track type 0 = one mesh driven by keyframes
(0x24 header, 0x50 per key: time, -, render id, pos xyz, rot xyz, quat[7], scale xyz, alpha); type 1 = a
particle emitter (struct at +0x14, see EMIT below; spawn FUN_8001f604, step FUN_8002147c / FUN_8008ada4).
Render id = 0x2000 + part + 1. Times are 30 Hz frames, angles 4096 per turn, scale / alpha 4096 = 1, y down.
Part flag 0x20000 (t29 part table, flags >> 16 & 2) marks camera-facing sprites. Pure stdlib; input is
bounds-checked.
"""
import glob
import os
import struct
import sys


def i32(d, o):
    return struct.unpack_from('<i', d, o)[0] if 0 <= o and o + 4 <= len(d) else 0


EMIT = ['flags', 'x', 'y', 'z', 'pool', 'rate', 'life', 'dur', 'v0', 'v1', 'mesh', 'radius', 'yaw0', 'yaw1',
        'pitch0', 'pitch1', 'ax', 'dx', 'ay', 'dy', 'az', 'dz', 'fadeIn', 'fadeOut', 'grow', 'shrink', 'spin',
        'respawn']


def scripts(d):
    n = i32(d, 0x48)
    if n <= 0 or n > 256:
        return []
    tab = 0x4c + i32(d, 0x4c)
    out = []
    for i in range(n):
        p = tab + 4 * i
        s = p + i32(d, p)
        nt, dur = i32(d, s), i32(d, s + 8)
        if not (0 <= nt <= 64) or s + 28 + 4 * nt > len(d):
            out.append(None)
            continue
        tracks = []
        for t in range(nt):
            q = s + 28 + 4 * t
            tr = q + i32(d, q)
            if i32(d, tr) == 0:
                nk = i32(d, tr + 16)
                if not (0 < nk <= 64) or tr + 0x24 + 0x50 * nk > len(d):
                    continue
                keys = []
                for k in range(nk):
                    K = [i32(d, tr + 0x24 + 0x50 * k + 4 * j) for j in range(20)]
                    keys.append([K[0], K[3], K[4], K[5], K[6] & 0xfff, K[7] & 0xfff, K[8] & 0xfff, K[16], K[17], K[18], K[19]])
                part = (i32(d, tr + 0x24 + 8) & 0xfff) - 1
                tracks.append(dict(part=part, end=i32(d, tr + 12), keys=keys))
            else:
                E = [i32(d, tr + 0x14 + 4 * j) for j in range(len(EMIT))]
                e = dict(zip(EMIT, E))
                e['part'] = (e.pop('mesh') & 0xfff) - 1
                e['life'] = e['life'] or i32(d, tr + 12)
                del e['flags']
                tracks.append(dict(emit=e))
        out.append(dict(dur=dur, tracks=tracks))
    return out


def bill(d):
    """part -> sprite mode from the part table flags (bit 17 = faces the camera, bit 16 seen on particles)."""
    n = min(i32(d, 0x54), 4096)
    return {k: (i32(d, 0x60 + 0x34 * k) >> 16) & 3 for k in range(n) if (i32(d, 0x60 + 0x34 * k) >> 16) & 3}


def js(v):
    if isinstance(v, dict):
        return '{' + ','.join(f'{k}:{js(x)}' for k, x in v.items()) + '}'
    if isinstance(v, list):
        return '[' + ','.join(js(x) for x in v) + ']'
    return 'null' if v is None else str(v)


def main(dat, out, specs):
    lines = ['// GENERATED by tools/fxscripts.py from the disc object packs. Do not edit; see re/notes/engine.md "Effect scripts".',
             "import type { FxPack } from './realFx';", '',
             'export const FX_PACKS: Record<number, FxPack> = {']
    for spec in specs:
        m, sep, sel = spec.partition(':')
        f = glob.glob(os.path.join(dat, f'{int(m):04d}.t29.bin'))
        if not f:
            sys.exit(f'model {m} not found in {dat}')
        d = open(f[0], 'rb').read()
        sc = scripts(d)
        keep = {int(x) for x in sel.split(',') if x} if sep else set(range(len(sc)))
        body = {i: s for i, s in enumerate(sc) if s and i in keep}
        lines.append(f'  {int(m)}: {{ bill: {js({k: v for k, v in bill(d).items()})}, scripts: {{')
        for i, s in body.items():
            lines.append(f'    {i}: {js(s)},')
        lines.append('  } },')
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
