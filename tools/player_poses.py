"""Bake 30 Hz player poses from the per-character script table in gameplay RAM captures."""
from pathlib import Path
import json
import struct

ROOT = Path(__file__).resolve().parents[1]
# Script numbers are engine-wide. Base character scripts come from Jungle Bash.
LEVEL_SCRIPTS = {
    0: [1, 2, 5, 6, 7, 8, 9, 10, 12, 14, 15, 16, 17, 18, 19],
    5: [0x57, 0x58, 0x59, 0x5a, 0x5b, 0x5c, 0x5d],
    10: list(range(0x2e, 0x33)),
    14: [0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1f, 0x20],
    18: [i for i in range(0x3a, 0x48) if i != 0x40],
    23: [0x48, 0x49, 0x4a, 0x4b, 0x52, 0x53, 0x54],
    27: [0x2b, 0x2c],
    28: list(range(0x4d, 0x51)),
}


def decode(ram, character, script, sample=None):
    def pointer(offset):
        return struct.unpack_from('<I', ram, offset)[0] - 0x80000000

    def word(offset):
        return struct.unpack_from('<H', ram, offset)[0]

    table = pointer(0x9d29c + character * 4)
    base = pointer(table + 4 * script)
    delay = word(base)
    pc = base + 2
    count = 1
    frames, visited, events = [], {}, {}
    loop = None
    while len(frames) < 4096:
        key = base, pc, count, delay
        if key in visited:
            loop = visited[key]
            break
        visited[key] = len(frames)
        op = word(pc)
        pc += 2
        if op < 0x8000:
            if op == 0:  # padding after a terminal event (e.g. kart respawn)
                break
            assert 0x2000 <= op < 0x6000, (character, script, hex(op))
            for i in range(count):
                pose = op + i if sample is None else sample(op + i, (pc - base) // 2 - 2)
                frames.extend([pose] * (1 + delay))
            count = 1
        elif op == 0x8000:
            pc = base + 2 + 2 * word(pc)
        elif op == 0x8001:
            base = pc
            pc += 2
        elif op == 0x8004 or op == 0x8005:  # next game state / script owned by the caller
            break
        elif op == 0x8007:
            count = word(pc)
            pc += 2
        elif op == 0x8018:
            delay = word(pc)
            pc += 2
        elif op in (0x8002, 0x8003):
            events[word(pc)] = len(frames)
            if op == 0x8002 and frames:
                frames += [frames[-1]] * (1 + delay)
            pc += 2
        elif op in (0x8006, 0x8008, 0x8009, 0x800a, 0x8019, 0x801a):
            pc += 2  # sound, model or movement flags, handled outside pose playback
        elif op not in (0x800b, 0x8017):
            raise ValueError((character, hex(script), hex(op)))
    assert 0 < len(frames) < 4096, (character, script)
    # Store consecutive or repeated poses as runs [first word, length, step].
    runs = []
    i = 0
    while i < len(frames):
        step = frames[i+1] - frames[i] if i+1 < len(frames) else 0
        end = i+1
        if step in (0, 1):
            while end < len(frames) and frames[end] == frames[i] + step*(end-i):
                end += 1
        else:
            step = 0
        runs.extend([frames[i], end-i, step])
        i = end
    return [len(frames), loop if loop is not None else -1, *runs], events


def player_poses():
    lines = ['// Generated by tools/player_poses.py. Per script and engine character (1..8).',
             '// Each track contains length, loop start (-1 holds the last frame), then pose/count/step runs.',
             'export const POSES: Record<number, number[][]> = {']
    for level, ids in LEVEL_SCRIPTS.items():
        ram = (ROOT / f're/dumps/L{level}.ram').read_bytes()
        for script in ids:
            tracks = [decode(ram, char, script)[0] for char in range(1, 9)]
            lines.append(f'  0x{script:02x}: [' + ',\n    '.join(json.dumps(t, separators=(',', ':')) for t in tracks) + '],')
    lines.append('};\n')
    ram = (ROOT / 're/dumps/L10.ram').read_bytes()
    lines.append('// FUN_800b5ee4 selects a pose directly while travelling to a tile.')
    lines.append('export const POGO_HOP: number[][] = [')
    for address, last in zip([0xc4758, 0xc4878, 0xc4ab0, 0xc49dc, 0xc4e40, 0xc4f3c, 0xc4ba0, 0xc4cf4], [17] * 7 + [16]):
        words = struct.unpack_from(f'<{last + 1}I', ram, address)
        lines.append('  [' + ', '.join(hex(word) for word in words) + '],')
    lines.append('];\n')
    # The secondary bear under the ice has a separate mesh and per-character render words.
    ram = (ROOT / 're/dumps/L18.ram').read_bytes()
    lines.append('// FUN_800cc3b4. Reflection words for dash and victory, indexed by the rider script clock.')
    lines.append('export const POLAR_REFLECTION_POSES: Record<number, number[][]> = {')
    for script in [0x3e, 0x46]:
        rows = []
        for char in range(1, 9):
            def sample(pose, pc):
                if script == 0x3e:
                    table = [0xd63b0, 0xd63b0, 0xd61d0, 0xd61d0, 0xd624c, 0xd624c, 0xd624c, 0xd62b4][char - 1]
                else:
                    table = [0xd6418, 0xd65f0, 0, 0xd66a8, 0xd6828, 0xd6760, 0xd64bc, 0xd6548][char - 1]
                    if not table:
                        return 0x4000
                    if char in (2, 4, 5, 6):
                        pc = max(0, pose - (0x4280 if char == 6 else 0x4300))
                return struct.unpack_from('<H', ram, table + pc * 4)[0]
            rows.append(decode(ram, char, script, sample)[0])
        lines.append(f'  0x{script:02x}: [' + ',\n    '.join(json.dumps(row, separators=(',', ':')) for row in rows) + '],')
    lines.append('};\n')
    (ROOT / 'web/client/games/playerPoseData.ts').write_text('\n'.join(lines))


def crate_grips():
    """Positions and rotations from the same per-pose model markers used by FUN_80015780."""
    ram = (ROOT / 're/dumps/L0.ram').read_bytes()
    chars = {p['id']: p['model'] for p in json.loads((ROOT / 'assets/catalog.json').read_text())['characters']}
    lines = ['// Generated by tools/player_poses.py. Character, pickup / hold / run / throw, then pose.',
             '// Native X, Y, Z coordinates of marker 1, or markers 0x10 and 0x20.',
             'export const CRATE_GRIPS: number[][][][] = [']
    ring_ram = (ROOT / 're/dumps/L27.ram').read_bytes()
    marker_tracks = {script: [] for script in (1,2,5,6,7,8,9,10,12,13,15,16,17,18,19,0x2b,0x2c)}
    glow_tracks = {script: [] for script in (15, 16, 17, 18)}
    bodies, attacks = [], []
    for char, name in enumerate(('crash', 'coco', 'cortex', 'brio', 'tiny', 'rilla', 'dingodile', 'koala'), 1):
        model = (ROOT / f'disc/dat/{chars[name]:04}.t29.bin').read_bytes()
        def word(offset):
            return struct.unpack_from('<I', model, offset)[0]
        def marker_table(pose):
            if pose & 0x7000 == 0x2000:
                ptr = 0x24 + (pose & 4095) * 52 + 0x2c
            else:
                assert pose & 0x7000 == 0x4000
                group = 0x44 + word(0x44) + ((pose & 0xf80) >> 7) * 24
                ptr = word(group) + ((pose & 127) + 1) * 16
            return ptr + word(ptr) if word(ptr) else 0
        def cylinder(pose, flag):
            ptr = marker_table(pose)
            points, shapes = struct.unpack_from('<HH', model, ptr)
            at = ptr + 4 + points * 8
            for x, bottom, z, radius, top, _, flags in struct.iter_unpack('<6hI', model[at:at + shapes*16]):
                if flags & flag:
                    return [x, -z, radius, -bottom, -top]
            raise ValueError((char, pose, flag))
        def grip(pose):
            ptr = marker_table(pose)
            markers = struct.iter_unpack('<3hH', model[ptr+4:ptr+4+8*struct.unpack_from('<H', model, ptr)[0]])
            points = {tag: xyz for *xyz, mask in markers for tag in (1, 16, 32) if mask & tag}
            return [*points[16], *points[32]] if 16 in points else points[1]
        def item_marker(pose, tag=0x80):
            ptr = marker_table(pose)
            if ptr:
                count = struct.unpack_from('<H', model, ptr)[0]
                for x, y, z, mask in struct.iter_unpack('<3hH', model[ptr+4:ptr+4+8*count]):
                    if mask & tag:
                        return [x, -y, z]
            return 0

        for script, rows in marker_tracks.items():
            source = ring_ram if script in (8, 12, 13, 0x2b, 0x2c) else ram
            track, _ = decode(source, char, script)
            offsets = [item_marker(w + j*step) for w, n, step in zip(track[2::3], track[3::3], track[4::3]) for j in range(n)]
            rows.append([track[1], *offsets] if any(offsets) else [-1, 0])
        for script, rows in glow_tracks.items():
            track, _ = decode(ram, char, script)
            offsets = [item_marker(w + j*step, 0x40) for w, n, step in zip(track[2::3], track[3::3], track[4::3]) for j in range(n)]
            rows.append([track[1], *offsets] if any(offsets) else [-1, 0])
        bodies.append(cylinder(0x2001, 0x40)[2:])
        attack, _ = decode(ram, char, 10)
        attacks.append([cylinder(w + j*step, 0x400) for w, n, step in zip(attack[2::3], attack[3::3], attack[4::3]) for j in range(n)])
        lines.append('  [')
        for script in range(15, 19):
            track, _ = decode(ram, char, script)
            poses = [grip(w + j * step) for w, n, step in zip(track[2::3], track[3::3], track[4::3]) for j in range(n)]
            # Place the loop index in the header of each track, including single-pose holds.
            lines.append('    ' + json.dumps([[track[1]], *poses], separators=(',', ':')) + ',')
        lines.append('  ],')
    lines.append('];\n')
    lines += ['// Body cylinder (radius, bottom, top) and per-frame attack cylinder (x, z, radius, bottom, top).',
              'export const CT_HULL: number[][] = ' + json.dumps(bodies, separators=(',', ':')) + ';',
              'export const CRATE_ATTACK: number[][][] = [',
              *['  ' + json.dumps(track, separators=(',', ':')) + ',' for track in attacks], '];\n']
    (ROOT / 'web/shared/games/crateGripData.ts').write_text('\n'.join(lines))

    lines = ['// Generated by tools/player_poses.py from marker 0x80. Axes are native X, height, Z.',
             '// Each track starts with its loop frame (-1 holds). Zero marks a pose without an attachment.',
             'type Marker = readonly [x: number, height: number, z: number];',
             'type MarkerTrack = readonly [loop: number, ...frames: (Marker | 0)[]];',
             'export const ON_FOOT_MARKERS: Record<number, readonly MarkerTrack[]> = {']
    for script, rows in marker_tracks.items():
        lines.append(f'  0x{script:02x}: [')
        lines.extend('    ' + json.dumps(row, separators=(',', ':')) + ',' for row in rows)
        lines.append('  ],')
    lines.append('};')
    lines.append('// Marker 0x40 (FUN_80015780 tag 0x40): where the crate states place the player object 0x8009d540.')
    lines.append('export const ON_FOOT_GLOW_MARKERS: Record<number, readonly MarkerTrack[]> = {')
    for script, rows in glow_tracks.items():
        lines.append(f'  0x{script:02x}: [')
        lines.extend('    ' + json.dumps(row, separators=(',', ':')) + ',' for row in rows)
        lines.append('  ],')
    lines.append('};\n')
    (ROOT / 'web/shared/games/onFootItemMarkers.ts').write_text('\n'.join(lines))


if __name__ == '__main__':
    player_poses()
    crate_grips()
