"""Pogo pose markers 0x80 (held item) and 0x200 (jet flame). `python3 re/notes/pogoPainter-markers.py emit`
rebuilds web/client/games/pogoMarkerData.ts; without arguments it prints marker counts per character."""
import struct, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'tools'))
from player_poses import decode
models = [974, 972, 970, 968, 966, 964, 962, 960]
ram = (ROOT/'re/dumps/L10.ram').read_bytes()
HOP = [0xc4758, 0xc4878, 0xc4ab0, 0xc49dc, 0xc4e40, 0xc4f3c, 0xc4ba0, 0xc4cf4]

def markers(model, pose):
    def word(o): return struct.unpack_from('<I', model, o)[0]
    if pose & 0x7000 == 0x2000:
        ptr = 0x24 + (pose & 4095) * 52 + 0x2c
    else:
        group = 0x44 + word(0x44) + ((pose & 0xf80) >> 7) * 24
        ptr = word(group) + ((pose & 127) + 1) * 16
    ptr = ptr + word(ptr) if word(ptr) else 0
    out = {}
    if ptr:
        count = struct.unpack_from('<H', model, ptr)[0]
        for x, y, z, mask in struct.iter_unpack('<3hH', model[ptr+4:ptr+4+8*count]):
            for m in (0x80, 0x200):
                if mask & m and m not in out: out[m] = (x, y, z)
    return out

def words_for(c):
    words = set()
    for s in (0x2e, 0x2f, 0x30, 0x31, 0x32):
        t, _ = decode(ram, c, s)
        for w, n, st in zip(t[2::3], t[3::3], t[4::3]):
            for j in range(n): words.add(w + j*st)
    words |= set(struct.unpack_from('<18I', ram, HOP[c-1]))
    return sorted(words)

if __name__ == '__main__':
    mode = sys.argv[1] if len(sys.argv) > 1 else 'stats'
    for c, mid in enumerate(models, 1):
        model = (ROOT/f'disc/dat/{mid:04}.t29.bin').read_bytes()
        ws = words_for(c)
        res = {w: markers(model, w) for w in ws}
        if mode == 'stats':
            print(c, mid, len(ws), 'm80', sum(0x80 in v for v in res.values()), 'm200', sum(0x200 in v for v in res.values()), hex(ws[0]), hex(ws[-1]))
            print('  ', [(hex(w), v) for w, v in list(res.items())[:4]])

def item_words(c):
    words = set()
    for s in (0x2e, 0x2f):
        t, _ = decode(ram, c, s)
        for w, n, st in zip(t[2::3], t[3::3], t[4::3]):
            for j in range(n): words.add(w + j*st)
    words |= set(struct.unpack_from('<18I', ram, HOP[c-1]))
    return sorted(words)

def emit():
    def row(table):
        return '{' + ','.join(f'0x{w:x}:[{x},{-y},{z}]' for w, (x, y, z) in table) + '}'
    lines = ['// Generated by re/notes/pogoPainter-markers.py from the eight USA pogo models (0974 ... 0960) and the',
             '// L10 script table. Native X, height and Z of the model markers that FUN_80015780 looks up per pose word.',
             'type Marker = readonly [x: number, height: number, z: number];',
             '/** Marker 0x80 (held item, FUN_800b76cc) per engine character, for the idle scripts and hop words. */',
             'export const POGO_ITEM_MARKER: Readonly<Record<number, Marker>>[] = [']
    jets = []
    for c, mid in enumerate(models, 1):
        model = (ROOT/f'disc/dat/{mid:04}.t29.bin').read_bytes()
        items = [(w, m[0x80]) for w in item_words(c) if 0x80 in (m := markers(model, w))]
        lines.append('  ' + row(items) + ',')
        if c in (3, 4):
            jets.append([(w, m[0x200]) for w in words_for(c) if 0x200 in (m := markers(model, w))])
    lines += ['];', '/** Marker 0x200 (jet flame, FUN_800b5b1c) for engine characters 3 and 4 in every Pogo script. */',
              'export const POGO_JET_MARKER: Readonly<Record<number, Marker>>[] = [']
    lines += ['  ' + row(j) + ',' for j in jets]
    lines.append('];\n')
    (ROOT/'web/client/games/pogoMarkerData.ts').write_text('\n'.join(lines))

if __name__ == '__main__' and len(sys.argv) > 1 and sys.argv[1] == 'emit':
    emit()
